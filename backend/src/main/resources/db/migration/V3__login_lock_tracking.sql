CREATE TABLE LAN_DANG_NHAP_SAI (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nguoi_dung_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id) ON DELETE CASCADE,
    thoi_diem TIMESTAMP NOT NULL
);

CREATE INDEX idx_lan_dang_nhap_sai_nguoi_dung_thoi_diem
    ON LAN_DANG_NHAP_SAI(nguoi_dung_id, thoi_diem);
