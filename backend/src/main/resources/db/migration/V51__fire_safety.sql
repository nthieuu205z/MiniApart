ALTER TABLE TOA_NHA ADD COLUMN pccc_chu_ky_thang INTEGER NOT NULL DEFAULT 6 CHECK (pccc_chu_ky_thang BETWEEN 1 AND 24);
ALTER TABLE TOA_NHA ADD COLUMN pccc_ngay_kiem_tra_tiep DATE NOT NULL DEFAULT CURRENT_DATE;

CREATE TABLE PCCC_HO_SO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toa_nha_id BIGINT NOT NULL REFERENCES TOA_NHA(id),
    phan_loai VARCHAR(50) NOT NULL CHECK (phan_loai IN ('THONG_TIN_CO_SO','PHUONG_AN_THOAT_NAN','BIEN_BAN_KIEM_TRA','THIET_BI','BAO_HIEM')),
    ten VARCHAR(255) NOT NULL,
    ten_tep VARCHAR(255) NOT NULL,
    loai_noi_dung VARCHAR(100) NOT NULL,
    du_lieu BYTEA NOT NULL CHECK (octet_length(du_lieu) <= 5242880),
    nguoi_tao_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_pccc_ho_so_toa ON PCCC_HO_SO(toa_nha_id);

CREATE TABLE PCCC_THIET_BI (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toa_nha_id BIGINT NOT NULL REFERENCES TOA_NHA(id),
    ten VARCHAR(255) NOT NULL,
    vi_tri VARCHAR(500) NOT NULL,
    han_kiem_dinh DATE NOT NULL
);
CREATE INDEX ix_pccc_thiet_bi_han ON PCCC_THIET_BI(toa_nha_id, han_kiem_dinh);

CREATE TABLE PCCC_KIEM_TRA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toa_nha_id BIGINT NOT NULL REFERENCES TOA_NHA(id),
    ngay_kiem_tra DATE NOT NULL,
    hang_muc TEXT NOT NULL,
    dat BOOLEAN NOT NULL,
    nguoi_tao_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id)
);
CREATE INDEX ix_pccc_kiem_tra_toa_ngay ON PCCC_KIEM_TRA(toa_nha_id, ngay_kiem_tra DESC);
