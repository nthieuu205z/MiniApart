-- V63: Schema for repair quotes with revisions and worker payments

CREATE SEQUENCE IF NOT EXISTS bao_gia_sua_chua_ma_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS thanh_toan_tho_ma_seq START WITH 1 INCREMENT BY 1;

-- 1. Table for repair quote versions
CREATE TABLE IF NOT EXISTS BAO_GIA_SUA_CHUA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_bao_gia VARCHAR(50) NOT NULL UNIQUE,
    yeu_cau_id BIGINT NOT NULL REFERENCES YEU_CAU_SUA_CHUA(id),
    phien_ban INTEGER NOT NULL DEFAULT 1 CHECK (phien_ban > 0),
    trang_thai VARCHAR(30) NOT NULL CHECK (
        trang_thai IN ('NHAP', 'CHO_DUYET', 'DA_DUYET', 'TU_CHOI', 'BI_THAY_THE')
    ),
    tong_tien NUMERIC(15,2) NOT NULL DEFAULT 0.00 CHECK (tong_tien >= 0),
    mo_ta TEXT NULL,
    ghi_chu TEXT NULL,
    ly_do_tu_choi TEXT NULL,
    nguoi_tao_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nguoi_duyet_id BIGINT NULL REFERENCES NGUOI_DUNG(id),
    duyet_luc TIMESTAMPTZ NULL,
    fixture_key VARCHAR(100) NULL,
    CONSTRAINT uq_bao_gia_yeu_cau_phien_ban UNIQUE (yeu_cau_id, phien_ban)
);

-- At most one active approved quote per repair request
CREATE UNIQUE INDEX IF NOT EXISTS uq_bao_gia_yeu_cau_da_duyet
    ON BAO_GIA_SUA_CHUA (yeu_cau_id)
    WHERE trang_thai = 'DA_DUYET';

CREATE INDEX IF NOT EXISTS idx_bao_gia_yeu_cau
    ON BAO_GIA_SUA_CHUA (yeu_cau_id);

CREATE INDEX IF NOT EXISTS idx_bao_gia_trang_thai
    ON BAO_GIA_SUA_CHUA (trang_thai);

CREATE INDEX IF NOT EXISTS idx_bao_gia_nguoi_tao
    ON BAO_GIA_SUA_CHUA (nguoi_tao_id);

-- 2. Line items for repair quotes
CREATE TABLE IF NOT EXISTS DONG_BAO_GIA_SUA_CHUA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bao_gia_id BIGINT NOT NULL REFERENCES BAO_GIA_SUA_CHUA(id) ON DELETE CASCADE,
    thu_tu INTEGER NOT NULL DEFAULT 1,
    ten_hang_muc VARCHAR(255) NOT NULL,
    so_luong NUMERIC(10,2) NOT NULL CHECK (so_luong > 0),
    don_vi VARCHAR(50) NOT NULL,
    don_gia NUMERIC(15,2) NOT NULL CHECK (don_gia >= 0),
    thanh_tien NUMERIC(15,2) NOT NULL CHECK (thanh_tien >= 0)
);

CREATE INDEX IF NOT EXISTS idx_dong_bao_gia_bao_gia
    ON DONG_BAO_GIA_SUA_CHUA (bao_gia_id);

-- 3. Worker payments table
CREATE TABLE IF NOT EXISTS THANH_TOAN_THO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_thanh_toan VARCHAR(50) NOT NULL UNIQUE,
    yeu_cau_id BIGINT NOT NULL REFERENCES YEU_CAU_SUA_CHUA(id),
    bao_gia_id BIGINT NULL REFERENCES BAO_GIA_SUA_CHUA(id),
    so_tien NUMERIC(15,2) NOT NULL CHECK (so_tien >= 0),
    phuong_thuc VARCHAR(30) NOT NULL CHECK (
        phuong_thuc IN ('TIEN_MAT', 'CHUYEN_KHOAN', 'KHONG_THU_PHI')
    ),
    ma_tham_chieu VARCHAR(100) NULL,
    nguoi_xac_nhan_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id),
    xac_nhan_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ghi_chu TEXT NULL,
    fixture_key VARCHAR(100) NULL
);

CREATE INDEX IF NOT EXISTS idx_thanh_toan_tho_yeu_cau
    ON THANH_TOAN_THO (yeu_cau_id);

CREATE INDEX IF NOT EXISTS idx_thanh_toan_tho_bao_gia
    ON THANH_TOAN_THO (bao_gia_id);

-- 4. Extend YEU_CAU_SUA_CHUA for survey notes, repair outcome, timestamps, and fixture key
ALTER TABLE YEU_CAU_SUA_CHUA
    ADD COLUMN IF NOT EXISTS ghi_chu_khao_sat TEXT NULL,
    ADD COLUMN IF NOT EXISTS ket_qua_sua_chua TEXT NULL,
    ADD COLUMN IF NOT EXISTS da_sua_xong_luc TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS dong_luc TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS fixture_key VARCHAR(100) NULL;

CREATE INDEX IF NOT EXISTS idx_yeu_cau_sua_chua_fixture_key
    ON YEU_CAU_SUA_CHUA (fixture_key);
