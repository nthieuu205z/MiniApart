-- Người thuê báo đã chuyển khoản: mỗi hoá đơn một dòng (idempotent), QL xác nhận bằng cách ghi thu như cũ.
CREATE TABLE BAO_DA_CHUYEN (
    hoa_don_id BIGINT PRIMARY KEY REFERENCES HOA_DON(id),
    nguoi_thue_id BIGINT NOT NULL REFERENCES NGUOI_THUE(id),
    bao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Ghi chú liên hệ giữa nhân viên và người thuê (gọi / Zalo / gặp).
CREATE TABLE GHI_CHU_LIEN_HE (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nguoi_thue_id BIGINT NOT NULL REFERENCES NGUOI_THUE(id),
    nguoi_tao_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id),
    kenh VARCHAR(10) NOT NULL CHECK (kenh IN ('GOI', 'ZALO', 'GAP')),
    noi_dung VARCHAR(1000) NOT NULL CHECK (length(btrim(noi_dung)) > 0),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_ghi_chu_lien_he_nguoi_thue ON GHI_CHU_LIEN_HE (nguoi_thue_id, tao_luc DESC, id DESC);
