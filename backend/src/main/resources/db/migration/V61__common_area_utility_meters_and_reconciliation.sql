-- V61: Bổ sung công tơ tổng, công tơ khu vực chung, đối soát điện nước và cảnh báo bất thường
-- Đảm bảo an toàn dữ liệu: giữ nguyên toàn bộ bảng và dữ liệu hiện có.

-- 1. Bảng điểm đo / công tơ (hỗ trợ công tơ tổng tòa nhà và công tơ khu vực chung)
CREATE TABLE IF NOT EXISTS DIEM_DO_DUNG_CHUNG (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toa_nha_id BIGINT NOT NULL REFERENCES TOA_NHA(id) ON DELETE CASCADE,
    ma_cong_to VARCHAR(50) NOT NULL,
    ten_cong_to VARCHAR(255) NOT NULL,
    loai_dich_vu VARCHAR(20) NOT NULL CHECK (loai_dich_vu IN ('DIEN', 'NUOC')),
    don_vi VARCHAR(20) NOT NULL CHECK (don_vi IN ('kWh', 'm3')),
    loai_diem_do VARCHAR(30) NOT NULL CHECK (loai_diem_do IN ('TONG', 'KHU_VUC_CHUNG')),
    khu_vuc VARCHAR(50) NOT NULL CHECK (khu_vuc IN ('TONG_TOA_NHA', 'HANH_LANG', 'THANG_MAY', 'MAY_BOM', 'GIAT_LA', 'BAI_XE', 'KHAC')),
    cong_to_cha_id BIGINT REFERENCES DIEM_DO_DUNG_CHUNG(id),
    don_gia_mua NUMERIC(15, 2) NOT NULL DEFAULT 0.00 CHECK (don_gia_mua >= 0),
    hoat_dong BOOLEAN NOT NULL DEFAULT TRUE,
    ngay_lap_dat DATE NOT NULL DEFAULT CURRENT_DATE,
    thoi_diem_tao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_diem_do_toa_ma UNIQUE (toa_nha_id, ma_cong_to)
);

CREATE INDEX IF NOT EXISTS idx_diem_do_toa_loai ON DIEM_DO_DUNG_CHUNG(toa_nha_id, loai_diem_do, loai_dich_vu);

-- 2. Bảng chỉ số ghi nhận cho điểm đo / công tơ chung
CREATE TABLE IF NOT EXISTS CHI_SO_DUNG_CHUNG (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diem_do_id BIGINT NOT NULL REFERENCES DIEM_DO_DUNG_CHUNG(id) ON DELETE CASCADE,
    ky_id BIGINT NOT NULL REFERENCES KY_THANH_TOAN(id) ON DELETE CASCADE,
    chi_so_dau NUMERIC(15, 2) NOT NULL CHECK (chi_so_dau >= 0),
    chi_so_cuoi NUMERIC(15, 2) NOT NULL CHECK (chi_so_cuoi >= 0),
    muc_tieu_thu NUMERIC(15, 2) NOT NULL CHECK (muc_tieu_thu >= 0),
    co_thay_cong_to BOOLEAN NOT NULL DEFAULT FALSE,
    chi_so_cuoi_cong_to_cu NUMERIC(15, 2) CHECK (chi_so_cuoi_cong_to_cu IS NULL OR chi_so_cuoi_cong_to_cu >= 0),
    chi_so_dau_cong_to_moi NUMERIC(15, 2) CHECK (chi_so_dau_cong_to_moi IS NULL OR chi_so_dau_cong_to_moi >= 0),
    nguoi_ghi_id BIGINT NOT NULL REFERENCES NGUOI_DUNG(id),
    thoi_diem_ghi TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ghi_chu TEXT,
    CONSTRAINT uq_chi_so_dung_chung_diem_ky UNIQUE (diem_do_id, ky_id),
    CONSTRAINT ck_chi_so_dung_chung_hop_le CHECK (
        (co_thay_cong_to = FALSE AND chi_so_cuoi >= chi_so_dau)
        OR (co_thay_cong_to = TRUE AND chi_so_cuoi_cong_to_cu IS NOT NULL AND chi_so_dau_cong_to_moi IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_chi_so_dung_chung_ky ON CHI_SO_DUNG_CHUNG(ky_id);

-- 3. Bảng cảnh báo bất thường tiêu thụ điện nước
CREATE TABLE IF NOT EXISTS CANH_BAO_TIEU_THU (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toa_nha_id BIGINT NOT NULL REFERENCES TOA_NHA(id) ON DELETE CASCADE,
    diem_do_id BIGINT REFERENCES DIEM_DO_DUNG_CHUNG(id) ON DELETE CASCADE,
    phong_id BIGINT REFERENCES PHONG(id) ON DELETE CASCADE,
    ky_id BIGINT NOT NULL REFERENCES KY_THANH_TOAN(id) ON DELETE CASCADE,
    loai_dich_vu VARCHAR(20) NOT NULL CHECK (loai_dich_vu IN ('DIEN', 'NUOC')),
    loai_canh_bao VARCHAR(50) NOT NULL CHECK (loai_canh_bao IN ('TIEU_THU_TANG_CAO', 'THIEU_CHI_SO', 'CHENH_LECH_DOI_SOAT', 'CHUA_DU_DU_LIEU')),
    muc_tieu_thu_ky_nay NUMERIC(15, 2),
    muc_tham_chieu NUMERIC(15, 2),
    muc_tang NUMERIC(15, 2),
    ty_le_tang NUMERIC(15, 2),
    ly_do TEXT NOT NULL,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'MOI_PHAT_HIEN' CHECK (trang_thai IN ('MOI_PHAT_HIEN', 'DANG_KIEM_TRA', 'DA_XU_LY')),
    nguoi_xac_nhan_id BIGINT REFERENCES NGUOI_DUNG(id),
    ghi_chu_xu_ly TEXT,
    thoi_diem_tao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_canh_bao_toa_trang_thai ON CANH_BAO_TIEU_THU(toa_nha_id, trang_thai);

