CREATE TABLE DAT_LAI_MAT_KHAU (
    nguoi_dung_id BIGINT PRIMARY KEY REFERENCES NGUOI_DUNG(id) ON DELETE CASCADE,
    ma_bi_mat_hash VARCHAR(255) NOT NULL,
    het_han TIMESTAMPTZ NOT NULL,
    so_lan_thu INTEGER NOT NULL DEFAULT 0 CHECK (so_lan_thu BETWEEN 0 AND 5),
    gui_luc TIMESTAMPTZ NOT NULL,
    cua_so_gui_luc TIMESTAMPTZ NOT NULL,
    so_lan_gui INTEGER NOT NULL DEFAULT 1 CHECK (so_lan_gui BETWEEN 1 AND 5),
    da_dung BOOLEAN NOT NULL DEFAULT FALSE
);
